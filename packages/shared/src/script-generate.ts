export function scriptGenerateSystemPrompt(provider: ScriptProviderKind = "fish"): string {
  return SCRIPT_CORE_RULES + (provider === "mimo" ? MIMO_DIALECT : FISH_DIALECT);
}

/** Fish-dialect system prompt (default historical path). */
export const SCRIPT_GENERATE_SYSTEM_PROMPT = scriptGenerateSystemPrompt("fish");

export function buildScriptGenerateUserPrompt(input: {
  instruction: string;
  sourceText?: string;
  provider?: ScriptProviderKind;
}): string {
  const instruction = input.instruction.trim();
  const source = input.sourceText?.trim() ?? "";
  const provider = input.provider ?? "fish";
  const parts: string[] = [];
  if (instruction) {
    parts.push(
      `## 用户指令\n下面是这次节目形态和额外要求。格式、说人话、边想边说这些基本要求，仍以系统说明为准。\n${instruction}`,
    );
  }
  if (source) {
    parts.push(
      provider === "mimo"
        ? `## 参考材料\n请根据下面材料改写成可导入的演播稿。保留要点，先说人话；对谈类请多写语气词，并在台词里自然嵌入 MiMo 的 (风格) 与 [音频标签]；不要写 Fish 的 [思考]/[停顿] 等。\n${source}`
        : `## 参考材料\n请根据下面材料改写成可导入的演播稿。保留要点，先说人话；对谈类请多写语气词，也把思考、停顿和情绪自然写进去。\n${source}`,
    );
  }
  if (!parts.length) {
    parts.push(
      provider === "mimo"
        ? "## 用户指令\n请生成一段可导入的演播稿示例。写成正在聊天时会说出口的话；语气词要有，并适当加入 MiMo 风格/音频标签。"
        : "## 用户指令\n请生成一段可导入的演播稿示例。写成正在聊天时会说出口的话，语气词和过程标记都可以自然多一点。",
    );
  }
  parts.push(
    provider === "mimo"
      ? "请直接输出完整演播稿正文，只输出会发声的台词行。写成边想边说的人话，并带上 MiMo 的 (风格)/[标签]；不要写风格指令长文，也不要写成 Fish 标签稿。"
      : "请直接输出完整演播稿正文，只输出会发声的台词行。写成边想边说的人话，不要写成干净的朗读稿。",
  );
  return parts.join("\n\n");
}

/** Strip common model wrappers so import parser sees plain script lines. */
export function normalizeGeneratedScript(raw: string): string {
  let text = raw.replace(/^\uFEFF/, "").replace(/\r\n/g, "\n").trim();
  // Fenced code block
  const fence = text.match(/^```(?:[\w-]+)?\n([\s\S]*?)\n```$/);
  if (fence?.[1]) text = fence[1].trim();
  // Leading "剧本：" / "演播稿：" labels
  text = text.replace(/^(?:剧本|演播稿|输出|结果)[：:]\s*/u, "");
  return text.trim();
}
